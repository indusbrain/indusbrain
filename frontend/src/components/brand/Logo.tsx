import React from 'react';
import './logo.css';

/**
 * IndusBrain logo.
 *
 * The symbol is a hex nut — the most recognisable piece of industrial
 * hardware — holding a branching signal: three inputs converging on one core.
 * That is the product in one glyph: many documents, one answer. The core is
 * the single accent-coloured element, so it reads as "the brain".
 *
 * Motion (see logo.css), transform / stroke-dashoffset only:
 *   load  — the nut is drawn, the branches run in, the nodes land, then the
 *           core lights.
 *   hover — the core pulses and the nodes answer one after another.
 *
 * Strokes are `currentColor` (so the mark is right on glass, on black, in both
 * themes) and the core uses the accent token. Static SVG exports of every
 * variant live in public/brand/ — generated by scripts/build-brand-assets.mjs,
 * whose geometry must be kept in step with the paths below.
 */

const stagger = (i: number) => ({ ['--i' as string]: i }) as React.CSSProperties;

export const LogoMark: React.FC<{
  size?: number;
  /** Play the draw-on sequence. Turn off where the mark repeats (e.g. lists). */
  animate?: boolean;
  className?: string;
  title?: string;
}> = ({ size = 32, animate = true, className, title }) => (
  <svg
    width={size}
    height={size}
    viewBox="0 0 32 32"
    fill="none"
    role={title ? 'img' : undefined}
    aria-hidden={title ? undefined : true}
    aria-label={title}
    className={['ib-mark', animate && 'ib-mark--animate', className].filter(Boolean).join(' ')}
  >
    <path
      className="ib-mark__hex"
      d="M16 2.6 27.6 9.3v13.4L16 29.4 4.4 22.7V9.3Z"
      stroke="currentColor"
      strokeWidth="2.4"
      strokeLinejoin="round"
    />
    <g stroke="currentColor" strokeWidth="2" strokeLinecap="round">
      <path className="ib-mark__branch" style={stagger(0)} d="M16 16V8.4" />
      <path className="ib-mark__branch" style={stagger(1)} d="M16 16 9.4 19.8" />
      <path className="ib-mark__branch" style={stagger(2)} d="M16 16l6.6 3.8" />
    </g>
    <g fill="currentColor">
      <circle className="ib-mark__node" style={stagger(0)} cx="16" cy="8" r="1.9" />
      <circle className="ib-mark__node" style={stagger(1)} cx="9" cy="20" r="1.9" />
      <circle className="ib-mark__node" style={stagger(2)} cx="23" cy="20" r="1.9" />
    </g>
    <circle className="ib-mark__core" cx="16" cy="16" r="3" fill="var(--color-accent)" />
  </svg>
);

export const Wordmark: React.FC<{ className?: string }> = ({ className }) => (
  <span className={['ib-wordmark', className].filter(Boolean).join(' ')}>
    <span className="ib-wordmark__light">indus</span>
    <span className="ib-wordmark__bold">brain</span>
  </span>
);

/** Full lockup: mark + wordmark. Hovering anywhere on it plays the pulse. */
export const Logo: React.FC<{
  size?: number;
  animate?: boolean;
  className?: string;
  tagline?: string;
}> = ({ size = 30, animate = true, className, tagline }) => (
  <span className={['ib-logo', className].filter(Boolean).join(' ')}>
    <LogoMark size={size} animate={animate} />
    <span className="flex min-w-0 flex-col">
      <Wordmark />
      {tagline && <span className="ib-logo__tagline">{tagline}</span>}
    </span>
  </span>
);
